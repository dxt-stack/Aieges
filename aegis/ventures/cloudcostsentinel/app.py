# In-memory data store for self-contained execution
ACCOUNTS_DB: Dict[str, Dict[str, Any]] = {
    "local_demo_token": {
        "account_id": "acc_demo",
        "plan": "Professional",
        "quota_limit": 15000,
        "quota_used": 142,
        "active": True
    }
}

TASKS_DB: List[Dict[str, Any]] = []


class IngestTaskRequest(BaseModel):
    payload: Dict[str, Any] = Field(description="Input data payload to be processed autonomously")
    priority: str = Field(default="NORMAL", description="NORMAL, HIGH, CRITICAL")
    webhook_callback_url: Optional[str] = None


class IngestTaskResponse(BaseModel):
    task_id: str
    status: str
    execution_latency_ms: float
    output: Dict[str, Any]
    remaining_quota: int


async def verify_api_key(credentials: HTTPAuthorizationCredentials = Security(security)):
    if not credentials:
        # Fallback to demo mode for testing
        return "local_demo_token"
    token = credentials.credentials
    if token not in ACCOUNTS_DB and token != "local_demo_token":
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or expired API Key. Acquire key from customer portal."
        )
    return token


