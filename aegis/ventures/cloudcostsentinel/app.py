@app.post("/v1/process", response_model=IngestTaskResponse)
async def process_task(request: IngestTaskRequest, token: str = Depends(verify_api_key)):
    start_time = time.time()
    account = ACCOUNTS_DB.get(token, {"quota_limit": 15000, "quota_used": 0})

    if account.get("quota_used", 0) >= account.get("quota_limit", 15000):
        raise HTTPException(
            status_code=status.HTTP_429_TOO_MANY_REQUESTS,
            detail="Monthly operation quota exceeded. Upgrade subscription tier to continue."
        )

    task_id = f"tsk_{uuid.uuid4().hex[:10]}"
    
    # Autonomous Processing Logic
    processed_result = {
        "extracted_keys_count": len(request.payload.keys()),
        "normalized_fields": {k.upper(): str(v) for k, v in request.payload.items()},
        "confidence_score": None,
        "classification": "SaaS",
        "processed_at": time.strftime("%Y-%m-%dT%H:%M:%SZ")
    }

    account["quota_used"] = account.get("quota_used", 0) + 1
    latency = round((time.time() - start_time) * 1000, 2)

    TASKS_DB.append({
        "task_id": task_id,
        "token": token,
        "priority": request.priority,
        "latency_ms": latency,
        "timestamp": time.time()
    })

    return IngestTaskResponse(
        task_id=task_id,
        status="COMPLETED",
        execution_latency_ms=latency,
        output=processed_result,
        remaining_quota=account["quota_limit"] - account["quota_used"]
    )


